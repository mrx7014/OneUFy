export function getItemsForOneUiVersion(isOneUi7Plus: boolean): Record<OverlayCategory, OverlayItem[]> {
  if (isOneUi7Plus) {
    return {
      wifi: WIFI_OVERLAYS_ONEUI7,
      signal: SIGNAL_OVERLAYS_ONEUI7,
      icons: [],
    };
  }
  return {
    wifi: WIFI_OVERLAYS_LEGACY,
    signal: SIGNAL_OVERLAYS_LEGACY,
    icons: ICON_PACKS,
  };
}

export const ALL_OVERLAYS: Record<OverlayCategory, OverlayItem[]> = {
  wifi: [...WIFI_OVERLAYS_ONEUI7, ...WIFI_OVERLAYS_LEGACY],
  signal: [...SIGNAL_OVERLAYS_ONEUI7, ...SIGNAL_OVERLAYS_LEGACY],
  icons: ICON_PACKS,
};

export function findOverlayByFilename(filename: string): OverlayItem | undefined {
  const all = [...WIFI_OVERLAYS_ONEUI7, ...WIFI_OVERLAYS_LEGACY, ...SIGNAL_OVERLAYS_ONEUI7, ...SIGNAL_OVERLAYS_LEGACY, ...ICON_PACKS];
  return all.find((item) => item.filename.toLowerCase() === filename.toLowerCase());
}

export function findOverlayById(id: string): OverlayItem | undefined {
  const all = [...WIFI_OVERLAYS_ONEUI7, ...WIFI_OVERLAYS_LEGACY, ...SIGNAL_OVERLAYS_ONEUI7, ...SIGNAL_OVERLAYS_LEGACY, ...ICON_PACKS];
  return all.find((item) => item.id === id);
}
